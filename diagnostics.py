#!/usr/bin/env python3
"""Evidence coverage diagnostics: discovered / parsed / skipped / empty / linked-to-cases per file.

    python code/diagnostics.py [--out evaluation/evidence_diagnostics.md]
"""
import argparse, csv, os, sys
from collections import Counter, defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = HERE if os.path.isdir(os.path.join(HERE, "dataset")) else os.path.dirname(HERE)
sys.path.insert(0, HERE)
import main as entry
from deletion_audit.model import fmt_ts


def collect(dataset):
    audit, reqs, _ = entry.run(dataset, "deletion_requests.csv")
    pool = list(reqs)
    views = audit.link(pool)
    disk = {}
    for d, _, fs in os.walk(os.path.join(dataset, "evidence")):
        for f in fs:
            disk[os.path.relpath(os.path.join(d, f), dataset).replace(os.sep, "/")] = os.path.join(d, f)
    nobs = Counter(o.file_id for o in audit.obs)
    linked = defaultdict(set)
    for v in views:
        q = v.req
        for (s, r) in v.resources:
            for o in audit.state.observations(s, r, fmt_ts(q.requested_at), fmt_ts(q.audit_at), True):
                linked[o.file_id].add(q.case_id)
    rows = []
    for fid, ef in audit.manifest.items():
        exists = ef.path in disk
        from deletion_audit.evidence.artifacts import EXTRACTION_LOG
        ex = EXTRACTION_LOG.get(os.path.join(dataset, ef.path))
        status = "missing-on-disk" if not exists else ("parsed" if nobs[fid] else "no-observations")
        if ex in ("empty", "error", "no-extractor"):
            status += f" (extraction {ex})"
        rows.append((fid, ef.kind, ef.path, ef.captured_at, status, nobs[fid], len(linked[fid])))
    listed = {ef.path for ef in audit.manifest.values()}
    unlisted = sorted(set(disk) - listed)
    return rows, unlisted, linkage(audit, views)


def linkage(audit, views):
    """Provenance of every linked resource: verified by identity keys vs inferred from activity timing.
    For inferred accounts also report how many worker deletions were eligible candidates (1 = uniquely determined)."""
    from deletion_audit.actlink import ACCOUNT_BAND, RESULT_FOR_STATUS, _m
    content_acc = {r for v in views for (sy, r), lr in v.resources.items() if sy == "account_service" and lr.link.startswith("content")}
    events = [e for e in audit.stream.worker if e.event_type == "DELETE_RECORD" and e.target == "account_service"
              and e.resource_id not in content_acc]
    side = []
    out = {"content": 0, "activity_analytics": 0, "activity_account_unique": 0, "activity_account_ambiguous": 0}
    amb = []
    for v in views:
        q = v.req
        for (sy, r), lr in v.resources.items():
            if lr.link.startswith("content"):
                out["content"] += 1
                side.append((q.case_id, sy, r, "verified", lr.link, ""))
            elif sy == "analytics_platform":
                out["activity_analytics"] += 1
                side.append((q.case_id, sy, r, "inferred", "activity-chain/band", ""))
            else:
                k = sum(1 for e in events if ACCOUNT_BAND[0] <= _m(e, q.reported_at) <= ACCOUNT_BAND[1]
                        and e.result == RESULT_FOR_STATUS[q.reported_status] and e.t <= q.audit_at)
                side.append((q.case_id, sy, r, "inferred", "activity-window", k))
                if k <= 1:
                    out["activity_account_unique"] += 1
                else:
                    out["activity_account_ambiguous"] += 1; amb.append((q.case_id, k))
    out["ambiguous_cases"] = amb
    out["_sidecar"] = side
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default=os.path.join(ROOT, "dataset"))
    ap.add_argument("--out", default=os.path.join(HERE, "evaluation", "evidence_diagnostics.md"))
    a = ap.parse_args()
    rows, unlisted, link = collect(a.dataset)
    kinds = Counter(r[1] for r in rows)
    st = Counter(r[4] for r in rows)
    lines = ["# Evidence diagnostics (generated by code/diagnostics.py)", "",
             f"Manifest files: {len(rows)}; by kind: {dict(sorted(kinds.items()))}",
             f"Status: {dict(sorted(st.items()))}; files on disk but not in manifest: {len(unlisted)}", "",
             "| file_id | kind | observations | cases linked | status |", "|---|---|---|---|---|"]
    for r in sorted(rows):
        lines.append(f"| {r[0]} | {r[1]} | {r[5]} | {r[6]} | {r[4]} |")
    lines += ["", "## Resource linkage provenance (hidden requests)", "",
              f"- linked by identity keys (email/hash/phone/user ref): {link['content']}",
              f"- inferred from activity timing, accounts: {link['activity_account_unique']} with a single eligible candidate, "
              f"{link['activity_account_ambiguous']} with several (resolved by constraint propagation, treat as uncertain)",
              f"- inferred from activity timing, anonymised analytics rows: {link['activity_analytics']}",
              "- ambiguous account cases (case, candidate count): " + ", ".join(f"{c}:{k}" for c, k in link['ambiguous_cases'][:60])]
    if unlisted:
        lines += ["", "Unlisted files: " + ", ".join(unlisted)]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(os.path.join(os.path.dirname(a.out), "linkage_confidence.csv"), "w", newline="") as fh:
        wr = csv.writer(fh, lineterminator="\n")
        wr.writerow(["case_id", "system_id", "resource_id", "link_status", "method", "eligible_candidates"])
        wr.writerows(sorted(link["_sidecar"]))
    open(a.out, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[:5]))
    print({k: v for k, v in link.items() if k not in ("ambiguous_cases", "_sidecar")})
    print("unparsed / unlinked:", [(r[0], r[1], r[4], r[5], r[6]) for r in rows if r[4] != "parsed" or r[6] == 0])

if __name__ == "__main__":
    main()
