#!/usr/bin/env python3
"""Ghost Data Still Exists - deletion-audit agent entry point.

    python code/main.py                      # audits dataset/deletion_requests.csv -> ./output.csv
    python code/main.py --evaluate           # also scores the public samples against sample_output.csv

Everything is resolved relative to the repository root, so it runs unchanged on macOS, Linux and Windows.
No network access and no API key is required: the pipeline is deterministic (see README.md).
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = HERE if os.path.isdir(os.path.join(HERE, "dataset")) else os.path.dirname(HERE)
sys.path.insert(0, HERE)

from deletion_audit.casemodel import load_requests          # noqa: E402
from deletion_audit.engine import Audit                       # noqa: E402
from deletion_audit.planner import dumps                      # noqa: E402
from deletion_audit.usage import METER                        # noqa: E402


def run(dataset: str, requests_file: str, extra=("sample_deletion_requests.csv",), omission: bool = True, strict_capture: bool = False):
    audit = Audit(dataset, omission=omission, strict_capture=strict_capture)
    reqs = load_requests(os.path.join(dataset, requests_file))
    pool = list(reqs)
    ids = {r.case_id for r in reqs}
    for f in extra:
        p = os.path.join(dataset, f)
        if os.path.exists(p) and f != requests_file:
            pool += [r for r in load_requests(p) if r.case_id not in ids]   # their events must not be stolen
    views = audit.link(pool)
    out = {}
    for v in views:
        status, steps = audit.audit(v)
        out[v.req.case_id] = (status, steps)
    return audit, reqs, out


def write_output(path: str, reqs, out) -> None:
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["case_id", "deletion_status", "steps_json"])
        for r in sorted(reqs, key=lambda r: r.case_id):
            status, steps = out[r.case_id]
            w.writerow([r.case_id, status, dumps(steps)])


def write_usage(n, seconds, counts):
    """Instrumented usage of the run that produced the output (zero unless a model call went through METER)."""
    from deletion_audit.evidence.artifacts import EXTRACTION_LOG
    t = METER.totals()
    rep = {"requests": n, "wall_seconds": round(seconds, 2), "status_counts": counts, "model_totals": t,
           "per_model": METER.models, "local_extractor_calls": len(EXTRACTION_LOG),
           "local_extractor_status": {k: sum(1 for v in EXTRACTION_LOG.values() if v == k) for k in set(EXTRACTION_LOG.values())}}
    d = os.path.join(HERE, "evaluation")
    with open(os.path.join(d, "usage_run.json"), "w", encoding="utf-8") as fh:
        json.dump(rep, fh, indent=2, default=dict)
    rows = "\n".join(f"| {m['provider']} | {k} | {m['calls']} | {m['input_tokens']} | {m['output_tokens']} | {m['cost_usd']:.4f} |"
                     for k, m in METER.models.items()) or "| none | none | 0 | 0 | 0 | 0.0000 |"
    md = f"""# Token usage and cost (instrumented)

Generated by `python code/main.py` from `evaluation/usage_run.json`; every model call must pass through
`deletion_audit/usage.py::METER`. The submitted pipeline contains no model client, so the counters are zero.

| Provider | Model | Calls | Input tokens | Output tokens | Est. cost (USD) |
|---|---|---|---|---|---|
{rows}
| **Overall** | | {t['calls']} | {t['input_tokens']} | {t['output_tokens']} | {t['cost_usd']:.4f} |

- Requests processed: {n} (status counts: {counts})
- Total tokens: {t['input_tokens'] + t['output_tokens']}; average per request: {(t['input_tokens'] + t['output_tokens']) / max(n, 1):.1f}
- Estimated cost: total {t['cost_usd']:.4f} USD; per request {t['cost_usd'] / max(n, 1):.4f} USD
- Wall time of this run: {seconds:.1f} s (CPU only, no network)
- Local, non-model extractors invoked (pdftotext / tesseract): {len(EXTRACTION_LOG)} files, status {rep['local_extractor_status']}
  (OCR text is cached by content hash in `.cache/ocr`; the first cold run performs the real extraction.)

No API keys or credentials are used or stored. Claude Code was used as the development assistant; that usage is not part of
the pipeline run summarised here.
"""
    with open(os.path.join(d, "usage_report.md"), "w", encoding="utf-8") as fh:
        fh.write(md)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", default=os.path.join(ROOT, "dataset"))
    ap.add_argument("--requests", default="deletion_requests.csv")
    ap.add_argument("--output", default=os.path.join(ROOT, "output.csv"))
    ap.add_argument("--evaluate", action="store_true", help="score the public samples as well")
    ap.add_argument("--strict-capture", action="store_true", help="ablation: ignore files captured after audit_at")
    ap.add_argument("--no-usage", action="store_true", help="do not rewrite evaluation/usage_*.{json,md}")
    ap.add_argument("--no-omission", action="store_true", help="ablation: disable absence-by-omission")
    a = ap.parse_args(argv)
    t0 = time.time()
    audit, reqs, out = run(a.dataset, a.requests, omission=not a.no_omission, strict_capture=a.strict_capture)
    write_output(a.output, reqs, out)
    counts = {}
    for st, _ in out.values():
        pass
    for r in reqs:
        counts[out[r.case_id][0]] = counts.get(out[r.case_id][0], 0) + 1
    if not a.no_usage:
        write_usage(len(reqs), time.time() - t0, counts)
    print(f"wrote {a.output}: {len(reqs)} rows {counts} in {time.time() - t0:.1f}s")
    if a.evaluate:
        from evaluate import evaluate, load
        _, sreqs, sout = run(a.dataset, "sample_deletion_requests.csv", extra=("deletion_requests.csv",),
                             omission=not a.no_omission, strict_capture=a.strict_capture)
        gold = load(os.path.join(a.dataset, "sample_output.csv"))
        print(json.dumps(evaluate(sout, gold), indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
